/*
 * Renders the original content (js/site-default.mjs) into the static files:
 *   - index.html          every <!-- build:NAME --> region (also the fallback page)
 *   - llms.txt, sitemap.xml
 *   - netlify/lib/templates.mjs   index.html as a string, for the site function
 *
 * Content edited in /admin doesn't need this — the site function renders it
 * live. Run it after changing index.html, the renderer or the default content:
 *
 *     node tools/build.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import SITE from "../js/site-default.mjs";
import { applyContent, renderLlms, SITE_URL } from "../js/site-render.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const file = (p) => path.join(ROOT, p);
const today = new Date().toISOString().slice(0, 10);

const html = applyContent(fs.readFileSync(file("index.html"), "utf8"), SITE, { strict: true, today });
fs.writeFileSync(file("index.html"), html);

const llms = renderLlms(SITE);
fs.writeFileSync(file("llms.txt"), llms);

fs.writeFileSync(file("sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
  <url>
    <loc>${SITE_URL}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>1.0</priority>
    <image:image><image:loc>${SITE_URL}assets/og.jpg</image:loc></image:image>
  </url>
  <url>
    <loc>${SITE_URL}resume</loc>
    <lastmod>${today}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>
  <url>
    <loc>${SITE_URL}llms.txt</loc>
    <lastmod>${today}</lastmod>
  </url>
</urlset>
`);

fs.mkdirSync(file("netlify/lib"), { recursive: true });
fs.writeFileSync(file("netlify/lib/templates.mjs"),
  "// Generated by tools/build.mjs — the page the site function fills in. Don't edit by hand.\n" +
  `export const HOME = ${JSON.stringify(html)};\n`);

console.log(`built: ${SITE.projects.length} projects, ${SITE.sections.length} sections → index.html, llms.txt, sitemap.xml, netlify/lib/templates.mjs`);
